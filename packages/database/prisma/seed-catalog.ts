/** Importação idempotente: nunca sobrescreve alterações já feitas pelo Admin. */
async function main() {
 const prisma = createPrismaClient();
 try {
  let created=0,existing=0;
  for(const row of records){
   const found=await prisma.catalogItem.findUnique({where:{importKey:row.importKey},select:{id:true}});
   if(found){existing++;continue;}
   await prisma.catalogItem.create({data:{...row}});
   created++;
  }
  console.log(`Catálogo importado: ${created} novos, ${existing} já existentes, ${records.length} no arquivo fonte.`);
 } finally {await prisma.$disconnect();}
}
main().catch(error=>{console.error(error);process.exitCode=1});
